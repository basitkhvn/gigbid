from __future__ import annotations

from typing import Any, Protocol


class MarketplaceAdapter(Protocol):
    """The ONE marketplace interface (R1). Implemented by GigSim and live Upwork adapters."""
    name: str

    async def search_jobs(self, user: str, q: str, category: str, skill: str, limit: int, offset: int) -> dict[str, Any]: ...
    async def get_job(self, user: str, job_id: str) -> dict[str, Any]: ...
    async def get_client(self, user: str, client_id: str) -> dict[str, Any]: ...
    async def get_connects(self, user: str) -> dict[str, Any]: ...
    async def get_price_stats(self, user: str, category: str) -> dict[str, Any]: ...
    async def get_policy(self, user: str) -> dict[str, Any]: ...
    async def list_messages(self, user: str, proposal_id: str) -> list[dict[str, Any]]: ...
    async def list_threads(self, user: str) -> dict[str, Any]: ...
    async def list_proposals(self, user: str) -> list[dict[str, Any]]: ...
    async def submit_proposal(self, user: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    async def send_message(self, user: str, payload: dict[str, Any]) -> dict[str, Any]: ...


class MarketplaceUnavailable(Exception):
    pass
