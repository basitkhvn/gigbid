"""Regenerates docs/RESULTS.md from evals/results/*.json. Every number in README/report is copied from this file."""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "results"
OUT = Path(__file__).resolve().parents[2] / "docs/RESULTS.md"


def load(n):
    p = R / n
    return json.loads(p.read_text()) if p.exists() else None


def fmt(x, d=3):
    return "n/a" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def main():
    L = ["# Results (auto-generated by `python -m evals.runners.make_tables`; source files in evals/results/)\n"]
    rag, outc, props = load("rag_results.json"), load("gigsim_outcomes.json"), {t: load(f"proposals_{t}.json") for t in ("open_flash", "open_v4pro")}
    if rag:
        L += ["## B5. RAG variants (dev set, 60 non-scam jobs per persona = 180)\n",
              "| Variant | Recall@5 | MRR | nDCG@10 | Recall@5 (>=4 reqs) | p95 latency (s) | GigSim reply rate (letter from top-5 items) |", "|---|---|---|---|---|---|---|"]
        for v, d in rag["variants"].items():
            o = d["overall"]
            rr = outc["by_variant"].get(v, {}).get("overall", {}).get("reply_rate") if outc else None
            L.append(f"| {v} | {fmt(o['recall5'])} | {fmt(o['mrr'])} | {fmt(o['ndcg10'])} | {fmt(o['recall5_ge4_reqs'])} | {fmt(o['p95_latency_s'])} | {fmt(rr)} |")
        if outc:
            for k in ("shipped_per_requirement", "generic_baseline"):
                if k in outc["by_variant"]:
                    L.append(f"| {k} | - | - | - | - | - | {fmt(outc['by_variant'][k]['overall']['reply_rate'])} |")
        L.append("\nBy persona (Recall@5 / nDCG@10):\n\n| Variant | ml | web | data |\n|---|---|---|---|")
        for v, d in rag["variants"].items():
            L.append(f"| {v} | " + " | ".join(f"{fmt(d['by_persona'][p]['recall5'])} / {fmt(d['by_persona'][p]['ndcg10'])}" for p in ("ml", "web", "data")) + " |")
    ab = load("ablation.json")
    if ab:
        L += ["\n## Ablation of the shipped pipeline (one component at a time)\n", "| Config | Recall@5 | nDCG@10 | Recall@5 (>=4 reqs) | p95 latency (s) |", "|---|---|---|---|---|"]
        for k, d in ab.items():
            o = d["overall"]; L.append(f"| {k} | {fmt(o['recall5'])} | {fmt(o['ndcg10'])} | {fmt(o['recall5_ge4_reqs'])} | {fmt(o['p95_latency_s'])} |")
    dec = load("decision_eval.json")
    if dec:
        o = dec["overall"]
        L += ["\n## Decisions (dev set, 200 jobs per persona, LLM-free triage path)\n", "| Persona | bid/skip F1 | scam P | scam R | price in band | injection flagged |", "|---|---|---|---|---|---|"]
        for p, d in dec["per_persona"].items():
            L.append(f"| {p} | {fmt(d['bid_or_skip']['f1'])} | {fmt(d['scam']['precision'])} | {fmt(d['scam']['recall'])} | {fmt(d['price_in_band'])} | {fmt(d['injection_detected'])} |")
        L.append(f"| **all** | {fmt(o['bid_or_skip']['f1'])} | {fmt(o['scam']['precision'])} | {fmt(o['scam']['recall'])} | {fmt(o['price_in_band'])} | {fmt(o['injection_detected'])} |")
        bf = load("decision_eval_before_fix.json")
        if bf:
            L.append(f"\nBefore the low-budget scam rule (failure-analysis fix): scam recall {fmt(bf['overall']['scam']['recall'])}, bid/skip F1 {fmt(bf['overall']['bid_or_skip']['f1'])}.")
    if any(props.values()):
        L += ["\n## Open-model configurations (full bid graph to approval; 8 good + 2 scam jobs per persona = 30 jobs)\n",
              "| Config | drafted | unsupported/proposal before -> after verification | critic loops | judge (1-5) | GigSim reply | p50 / p95 latency (s) | tokens/job | USD/proposal |", "|---|---|---|---|---|---|---|---|---|"]
        for t, d in props.items():
            if d:
                s = d["summary"]
                L.append(f"| {t} | {s['n_drafted']} | {fmt(s['unsupported_per_proposal_before'])} -> {fmt(s['unsupported_per_proposal_after'])} | {fmt(s['critic_loops_mean'])} | {fmt(s.get('judge_score_mean'))} (n={s.get('judge_n')}) | {fmt(s['reply_rate'])} (n={s['n_sent']}) | {fmt(s['p50_latency_s'])} / {fmt(s['p95_latency_s'])} | {fmt(s['tokens_per_job'], 0)} | {fmt(s['usd_per_proposal'], 4)} |")
        L.append("\nUSD uses placeholder prices in agent/config.yaml (verify against the provider's price list before citing).")
    td = load("tool_design.json")
    if td:
        L += [f"\n## R&D A: tool granularity ({td['n_tasks']} tasks, model {td['model']})\n", "| Design | #tools | tool-selection acc | argument acc | tokens/task |", "|---|---|---|---|---|"]
        for k, d in td["designs"].items():
            L.append(f"| {k} | {d['n_tools']} | {fmt(d['tool_selection_acc'])} | {fmt(d['argument_acc'])} | {fmt(d['tokens_per_task'], 0)} |")
    ac = load("agent_comparison.json")
    if ac:
        L += [f"\n## R&D C: single agent vs supervisor vs hand-built graph ({ac['n_jobs']} dev jobs: good/weak/scam/injection mix)\n",
              "| System | bid/skip acc | scams wrongly bid | ungrounded skill claims/proposal | violations in final text | GigSim reply | tokens/job | USD/job | p95 latency (s) |", "|---|---|---|---|---|---|---|---|---|"]
        for k, d in ac["systems"].items():
            L.append(f"| {k} | {fmt(d['bid_or_skip_acc'])} | {d['scams_wrongly_bid']} | {fmt(d['ungrounded_skill_claims_per_proposal'])} | {fmt(d['violations_in_final_per_proposal'])} | {fmt(d['reply_rate'])} (n={d['n_proposals']}) | {fmt(d['tokens_per_job'], 0)} | {fmt(d['usd_per_job'], 4)} | {fmt(d['p95_latency_s'])} |")
        L.append("\nBy job kind (bid/skip accuracy): " + "; ".join(f"{k}: " + ", ".join(f"{kk} {vv}" for kk, vv in d["by_kind_acc"].items()) for k, d in ac["systems"].items()))
    inj = load("injection_eval.json")
    if inj:
        L += [f"\n## E4: prompt-injection attack success rate ({inj['n_jobs']} planted-injection jobs)\n", "| Defences | drafted | ASR |", "|---|---|---|"]
        for k, d in inj["conditions"].items():
            L.append(f"| {k} | {d['n_drafted']} | {fmt(d['asr'])} |")
    x2 = load("ab_experiment.json")
    if x2:
        L += ["\n## X2: proposal A/B experiment in GigSim\n", f"A = {x2['strategy_A']}; B = {x2['strategy_B']}; n={x2['n_jobs']} paired jobs.\n",
              f"Reply rate A {fmt(x2['reply_A'])} vs B {fmt(x2['reply_B'])}; Fisher exact p={x2['fisher_exact_p']:.2e}; paired exact McNemar p={x2['mcnemar_exact_p_paired']:.2e}. {x2['caveat']}"]
    jc = load("judge_calibration.json")
    L.append("\n## Judge calibration\n" + (f"Cohen's kappa (binary good>=4): {jc['kappa_binary_good_ge4']}; quadratic-weighted: {jc['kappa_quadratic_1to5']}; n={jc['n']}." if jc else
             "**PENDING: the 30 human labels have not been entered** (evals/datasets/judge_calibration_sheet.csv). Judge-based numbers above are uncalibrated until `judge_calibration kappa` is run."))
    OUT.write_text("\n".join(L) + "\n")
    rd = OUT.parents[1] / "README.md"
    if rd.exists():
        t = rd.read_text()
        a, b = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
        if a in t and b in t:
            body = "\n".join(L[1:]).replace("\n## ", "\n#### ").replace("## B5", "#### B5")
            rd.write_text(t.split(a)[0] + a + "\n" + body + "\n" + b + t.split(b)[1])
    print("wrote", OUT)


if __name__ == "__main__":
    main()
